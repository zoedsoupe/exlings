# Comentários
#
# Comentários são anotações no seu código que são ignoradas pelo computador.
# Elas existem para humanos lerem e entenderem o que o código faz!
#
# Em Elixir, existe apenas um tipo de comentário: o comentário de linha.
#
# Comentários de linha:
# - Começam com o símbolo #
# - Tudo depois do # naquela linha é ignorado
# - Ótimos para explicar seu código para outras pessoas (e para o seu eu do futuro!)
#
# Exemplos:
#   # Isso é um comentário
#   IO.puts("Hello")  # Isso também é um comentário (depois do código)
#
# Dica profissional: bons comentários explicam POR QUE você fez algo,
# não apenas O QUE o código faz. O código em si já mostra O QUE ele faz!
